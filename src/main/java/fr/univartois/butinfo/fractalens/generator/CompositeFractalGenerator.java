package fr.univartois.butinfo.fractalens.generator;

import com.madgag.gif.fmsware.AnimatedGifEncoder;
import fr.univartois.butinfo.fractalens.image.IFractalImage;

import java.awt.Color;
import java.awt.image.BufferedImage;
import java.util.ArrayList;
import java.util.List;

/**
 * The CompositeFractalGenerator class is a composite of {@link IFractalGenerator},
 * used to generate an animation.
 *
 * It contains a list of generators, each of them producing one frame of the
 * animation. Generating the image of the composite generates the images of all its
 * generators, and saving it gathers these images into an animated GIF.
 *
 *
 * @version 0.1.0
 */
public class CompositeFractalGenerator implements IFractalGenerator {

  /**
   * The generators producing the frames of the animation, in order.
   */
  private final List<IFractalGenerator> generators;

  /**
   * The delay between two frames of the animation (in milliseconds).
   */
  private final int delay;

  /**
   * The name of the GIF file in which the animation is saved.
   */
  private final String outputFile;

  /**
   * The images generated by the generators, used as the frames of the animation.
   */
  private final List<BufferedImage> images = new ArrayList<>();

  /**
   * Creates a new CompositeFractalGenerator.
   *
   * @param generators The generators producing the frames of the animation, in order.
   * @param delay The delay between two frames of the animation (in milliseconds).
   * @param outputFile The name of the GIF file in which the animation is saved.
   */
  public CompositeFractalGenerator(List<IFractalGenerator> generators, int delay, String outputFile){
    this.generators = generators;
    this.delay = delay;
    this.outputFile = outputFile;
  }

  /**
   * Generates the images of all the generators of this composite, and keeps them as
   * the frames of the animation.
   *
   * @return The image of the last frame, or {@code null} if there is no generator.
   *
   * @see IFractalGenerator#generateImage()
   */
  @Override
  public IFractalImage generateImage() {
    images.clear();
    IFractalImage last = null;

    for (int i = 0; i < generators.size(); i++) {
      IFractalImage image = generators.get(i).generateImage();
      images.add(image.asBufferedImage());
      last = image;
    }
    return last;
  }

  /**
   * Computing the color of a single pixel has no meaning for an animation, which is
   * made of several images.
   *
   * @param row The row of the pixel.
   * @param column The column of the pixel.
   *
   * @return Never returns normally.
   *
   * @throws UnsupportedOperationException Always, since this operation is not
   *         supported by a composite.
   *
   * @see IFractalGenerator#computePixelColor(int, int)
   */
  @Override
  public Color computePixelColor(int row, int column) {
    throw new UnsupportedOperationException(
            "composite generator cannot compute a single pixel color.");
  }

  /**
   * Saves the generated frames as an animated GIF in the output file. The animation
   * loops forever.
   *
   * @see IFractalGenerator#saveImage()
   */
  @Override
  public void saveImage() {
    AnimatedGifEncoder animatedGif = new AnimatedGifEncoder();
    animatedGif.start(outputFile);
    animatedGif.setDelay(delay);
    animatedGif.setRepeat(0);
    animatedGif.setQuality(5); // if number small, more quality but take more time

    for ( BufferedImage image : images){
      animatedGif.addFrame(image);
    }
    animatedGif.finish();
  }
}